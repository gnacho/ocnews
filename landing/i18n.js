let currentLang = localStorage.getItem('ocnews-lang') || (navigator.language.startsWith('es') ? 'es' : 'en');

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let s = dict[key] ?? I18N.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => { s = s.replaceAll(`{${k}}`, v); });
  }
  return s;
}

function applyLang() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const value = t(key);
    if (el.tagName === 'META') el.content = value;
    else if (el.tagName === 'TITLE') document.title = value;
    else if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = value;
    else if (el.tagName === 'IMG') el.alt = value;
    else el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key);
  });
  const langBtn = document.getElementById('langBtn');
  if (langBtn) langBtn.textContent = currentLang.toUpperCase();
  const ogLocales = document.querySelectorAll('meta[property^="og:locale"]');
  ogLocales.forEach(m => {
    if (m.getAttribute('property') === 'og:locale') m.content = currentLang === 'es' ? 'es_ES' : 'en_US';
  });
}

function setLang(lang) {
  currentLang = lang === 'es' ? 'es' : 'en';
  localStorage.setItem('ocnews-lang', currentLang);
  applyLang();
  const event = new CustomEvent('ocnews:langchange', { detail: currentLang });
  document.dispatchEvent(event);
}
